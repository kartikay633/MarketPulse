/**
 * Intelligent typeahead search function for Indian Equities
 * Prioritizes:
 * 1. Exact or prefix match on ticker symbol (e.g. "TAT" -> TATAMOTORS, TATASTEEL)
 * 2. Prefix match on company name (e.g. "Tata" -> Tata Motors, Tata Steel, Tata Consultancy)
 * 3. Substring match on ticker symbol or company name
 * 4. Keyword / sector match
 */
export function searchEquities(query, limit = 8) {
  if (!query || typeof query !== 'string') return [];
  const q = query.trim().toLowerCase();
  if (q.length === 0) return [];

  const cleanQuery = q.replace(/^nse:|^bse:/, '');

  const scored = EQUITIES_UNIVERSE.map((stock) => {
    const rawTicker = stock.symbol.replace(/^NSE:|^BSE:/, '').toLowerCase();
    const nameLower = stock.name.toLowerCase();
    const shortNameLower = (stock.shortName || '').toLowerCase();
    let score = 0;

    // 1. Symbol match
    if (rawTicker === cleanQuery) {
      score += 100;
    } else if (rawTicker.startsWith(cleanQuery)) {
      score += 80;
    } else if (rawTicker.includes(cleanQuery)) {
      score += 50;
    }

    // 2. Company name match
    if (nameLower.startsWith(cleanQuery) || shortNameLower.startsWith(cleanQuery)) {
      score += 70;
    } else {
      const words = nameLower.split(/\s+/);
      if (words.some((w) => w.startsWith(cleanQuery))) {
        score += 60;
      } else if (nameLower.includes(cleanQuery)) {
        score += 40;
      }
    }

    // 3. Keywords match
    if (stock.keywords && stock.keywords.some((k) => k.startsWith(cleanQuery))) {
      score += 30;
    } else if (stock.keywords && stock.keywords.some((k) => k.includes(cleanQuery))) {
      score += 15;
    }

    // 4. Sector match
    if (stock.sector.toLowerCase().includes(cleanQuery)) {
      score += 10;
    }

    return { stock, score };
  });

  return scored
    .filter((item) => item.score > 0)
    .sort((a, b) => b.score - a.score)
    .slice(0, limit)
    .map((item) => item.stock);
}
